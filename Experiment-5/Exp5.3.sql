DO$$
DECLARE
VAR INT:=15;
    BEGIN
    IF VAL>=1 && VAL<=10 THEN
    RAISE NOTICE 'YOUR VALUE IS % AND RANGE IS BETWEEN 1 TO 10',VAL;

    ELSIF VAL>10 AND VAL<=20 THEN
    RAISE NOTICE 'YOUR VALUE IS % AND RANGE IS BETWEEN 11 TO 20',VAL;

    ELSIF VAL>20 AND VAL<=30 THEN
    RAISE NOTICE 'YOUR VALUE IS % AND RANGE IS BETWEEN 21 TO 30',VAL;

    ELSE
    RAISE NOTICE 'YOUR VALUE IS % AND VALUE IS GREATOR THAN 30',VAL;

    END IF;
    END;
$$
